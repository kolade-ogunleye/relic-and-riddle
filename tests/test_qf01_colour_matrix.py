def test_the_gold_caption_word_is_bt709_brand_gold_in_the_master(tmp_path, narration, monkeypatch):
    """libass writes an ASS file's colours with the matrix its header names (none: TV.601). The master is BT.709,
    so the composer's header says TV.709: the gold key word is BT.709 brand gold, not BT.601's values in a BT.709
    master (which decode about (250, 180, 42))."""
    from src import brand
    grey = graphics._encode((Image.new("RGB", (1080, 1920), (128, 128, 128)) for _ in range(75)),
                            tmp_path / "grey.mp4", 75, 1080, 1920)
    monkeypatch.setattr(vc, "film_grade_filter", lambda *a, **k: "null")
    monkeypatch.setattr(vc, "picture_vignette", lambda *a, **k: "null")
    out = tmp_path / "master.mp4"
    words = [{"word": "The", "start": 0.2, "dur": 0.3}, {"word": "GOLDEN", "start": 0.5, "dur": 0.6},
             {"word": "gate.", "start": 1.1, "dur": 0.4}]
    vc.VideoComposer().compose_video([grey], narration, narration, words, 2.0, out, emphasis=["GOLDEN"],
                                     delivery_profile=get_delivery_profile("reel"))
    w, h = 1080, 1920
    raw = subprocess.run(["ffmpeg", "-v", "error", "-ss", "0.8", "-i", str(out), "-frames:v", "1",
                          "-f", "rawvideo", "-pix_fmt", "yuv420p", "-"], capture_output=True, check=True,
                         timeout=120).stdout
    a = np.frombuffer(raw, np.uint8)
    y = a[:w * h].reshape(h, w)[::2, ::2].astype(float)
    u = a[w * h:w * h * 5 // 4].reshape(h // 2, w // 2).astype(float)
    v = a[w * h * 5 // 4:w * h * 3 // 2].reshape(h // 2, w // 2).astype(float)
    gold = (u < 80) & (v > 150) & (y > 150)    # the glyph cores of the gold word (grey is U128 V128)
    assert gold.sum() > 200, gold.sum()
    got = (float(np.median(y[gold])), float(np.median(u[gold])), float(np.median(v[gold])))
    expected = _bt709(brand.GOLD)
    assert all(abs(g - e) <= TOL for g, e in zip(got, expected)), (got, expected)
