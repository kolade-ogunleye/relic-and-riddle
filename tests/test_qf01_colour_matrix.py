def test_an_untagged_sd_film_is_read_as_bt601_and_delivered_bt709(tmp_path):
    """Archive SD film is BT.601 and often untagged: the segment converts it, it does not just relabel it."""
    src = tmp_path / "film.mp4"
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i", "color=c=0xFF0000:s=320x240:r=30",
                    "-t", f"{footage.SEGMENT_SECONDS + 0.5:.2f}",
                    "-vf", "format=rgb24,scale=out_color_matrix=bt601:out_range=tv,format=yuv420p",
                    "-c:v", "libx264", "-preset", "ultrafast", "-crf", "1", str(src)], check=True, timeout=120)
    seg = footage.make_segment(src, footage.probe(src), tmp_path / "footage_01.mp4")
    _assert_bt709(seg, t=0.5)


