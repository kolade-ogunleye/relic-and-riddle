def test_the_master_delivers_bt709_red_from_a_still_and_a_graphic(tmp_path, narration, monkeypatch):
    """The composer's own graph with the grade held at identity, so the colour conversions are measured alone:
    the 16:9 portrait still (its tilt branch has no tone curve) and a graphic clip both arrive as BT.709 red."""
    still = tmp_path / "red_still.png"
    Image.new("RGB", (600, 800), RED).save(still)
    gfx = graphics._encode((Image.new("RGB", (1920, 1080), RED) for _ in range(40)), tmp_path / "gfx.mp4", 40,
                           1920, 1080)
    monkeypatch.setattr(vc, "film_grade_filter", lambda *a, **k: "null")
    out = tmp_path / "master.mp4"
    vc.VideoComposer().compose_video([still, gfx], narration, narration, [{"word": "Red.", "start": 0.2, "dur": 0.4}],
                                     2.0, out, durations=[1.0, 1.0],
                                     delivery_profile=get_delivery_profile("deep_dive"))
    _assert_bt709(out, t=0.3)    # the still
    _assert_bt709(out, t=1.7)    # the graphic


