"""QF-01 (2026-11-05): one colour matrix, BT.709 limited range, from every intermediate clip to the master.

swscale converts RGB to YUV with BT.601 unless told otherwise, and the master is tagged BT.709: a pure red graphic
measured Y81 U90 V240 in its clip (BT.709 red is Y63 U102 V240) and the master's primaries and transfer were left
unknown. Every input here is generated by the test (solid #FF0000 frames, a solid red source, a sine narration).
"""
import json
import subprocess

import numpy as np
import pytest
from PIL import Image

from src import footage, graphics, parallax
from src import video_composer as vc
from src.delivery_profiles import get_delivery_profile

RED = (255, 0, 0)
BT709_RED = (63, 102, 240)
TOL = 2


def _tags(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries",
                          "stream=color_space,color_primaries,color_transfer,color_range", "-of", "json", str(path)],
                         capture_output=True, text=True, check=True, timeout=60)
    s = json.loads(out.stdout)["streams"][0]
    return s.get("color_space"), s.get("color_primaries"), s.get("color_transfer"), s.get("color_range")


def _yuv(path, t=0.0, box=24):
    """Centre Y, U, V of the frame at `t`, read from the file's own yuv420p planes (no conversion)."""
    w, h = (int(x) for x in subprocess.run(
        ["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height",
         "-of", "csv=s=x:p=0", str(path)], capture_output=True, text=True, check=True, timeout=60).stdout.split("x"))
    raw = subprocess.run(["ffmpeg", "-v", "error", "-ss", f"{t:.3f}", "-i", str(path), "-frames:v", "1",
                          "-f", "rawvideo", "-pix_fmt", "yuv420p", "-"], capture_output=True, check=True,
                         timeout=120).stdout
    a = np.frombuffer(raw, np.uint8)
    y = a[:w * h].reshape(h, w)
    u = a[w * h:w * h * 5 // 4].reshape(h // 2, w // 2)
    v = a[w * h * 5 // 4:w * h * 3 // 2].reshape(h // 2, w // 2)
    cy, cx, b = h // 2, w // 2, box // 2
    return (float(y[cy - box:cy + box, cx - box:cx + box].mean()),
            float(u[cy // 2 - b:cy // 2 + b, cx // 2 - b:cx // 2 + b].mean()),
            float(v[cy // 2 - b:cy // 2 + b, cx // 2 - b:cx // 2 + b].mean()))


def _bt709(rgb):
    r, g, b = (c / 255.0 for c in rgb)
    y = 0.2126 * r + 0.7152 * g + 0.0722 * b
    return 16 + 219 * y, 128 + 224 * (b - y) / 1.8556, 128 + 224 * (r - y) / 1.5748


def _assert_bt709(path, expected=BT709_RED, t=0.0):
    assert _tags(path) == ("bt709", "bt709", "bt709", "tv"), (path.name, _tags(path))
    got = _yuv(path, t)
    assert all(abs(g - e) <= TOL for g, e in zip(got, expected)), (path.name, got, expected)


