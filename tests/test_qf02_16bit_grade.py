"""QF-02 (2026-11-06): the master's picture chain runs in 16-bit RGB, and its black is video black.

curves and lut3d are RGB filters; on the yuv420p stream ffmpeg converted to 8-bit RGB and back around each, and a
0-64 shadow ramp (56 luma levels) came out of the master with 29-31 levels; three stacked black lifts (a still's
branch curve, the pre-LUT curve, the print table's black) put black at Y21-22. Every input here is generated by the
test (flat BT.709 frames, black stills, a sine narration); the master's encoder is pinned lossless so the graph's
own output is measured.
"""
import subprocess

import numpy as np
import pytest
from PIL import Image

from src import video_composer as vc
from src.delivery_profiles import get_delivery_profile

W, H = 1080, 1920
LEVELS = list(range(16, 72))      # the luma codes of RGB 0..64, BT.709 limited range
PER_LEVEL = 3
TAGS = ["-colorspace", "bt709", "-color_primaries", "bt709", "-color_trc", "bt709", "-color_range", "tv"]


@pytest.fixture
def lossless(monkeypatch):
    monkeypatch.setattr(vc, "_get_video_encoder", lambda: ["-c:v", "libx264", "-preset", "ultrafast", "-qp", "0"])


def _sine(path, seconds):
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i", "sine=frequency=220:sample_rate=48000",
                    "-af", "volume=0.3", "-ac", "1", "-t", f"{seconds + 0.5:.2f}", str(path)], check=True, timeout=60)
    return path


def _ramp_clip(path):
    """Flat frames stepping through LEVELS (yuv420p, tagged BT.709), losslessly encoded."""
    uv = np.full((H // 2, W // 2), 128, np.uint8).tobytes()
    raw = b"".join((np.full((H, W), y, np.uint8).tobytes() + uv + uv) * PER_LEVEL for y in LEVELS)
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "rawvideo", "-pix_fmt", "yuv420p", "-s", f"{W}x{H}", "-r", "30",
                    "-i", "-", "-vf", "setparams=range=tv:color_primaries=bt709:color_trc=bt709:colorspace=bt709",
                    "-c:v", "libx264", "-qp", "0", "-preset", "ultrafast", "-pix_fmt", "yuv420p", *TAGS, str(path)],
                   input=raw, check=True, timeout=300)
    return path


def _compose(tmp_path, scenes, seconds, profile="reel"):
    vo = _sine(tmp_path / "vo.wav", seconds)
    out = tmp_path / "master.mp4"
    vc.VideoComposer().compose_video(scenes, vo, vo, [{"word": "Dark.", "start": 0.2, "dur": 0.4}], seconds, out,
                                     durations=[seconds], delivery_profile=get_delivery_profile(profile))
    return out


def _centre_means(path, w, h, box=96):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(path), "-f", "rawvideo", "-pix_fmt", "yuv420p", "-"],
                         capture_output=True, check=True, timeout=600).stdout
    n = w * h * 3 // 2
    a = np.frombuffer(raw, np.uint8)
    return [float(a[i * n:i * n + w * h].reshape(h, w)[h // 2 - box:h // 2 + box, w // 2 - box:w // 2 + box].mean())
            for i in range(len(a) // n)]


def test_a_shadow_ramp_keeps_its_levels_through_grade_lut_vignette_and_captions(tmp_path, lossless):
    """56 shadow levels in, at least 50 still distinct in the master (the start commit kept 29: 8-bit round trips
    merged neighbours onto one code; the 16-bit chain's dithered conversion keeps a fractional step)."""
    clip = _ramp_clip(tmp_path / "ramp_01.mp4")
    master = _compose(tmp_path, [clip], len(LEVELS) * PER_LEVEL / 30)
    means = _centre_means(master, W, H)
    per_level = [means[k * PER_LEVEL + 1] for k in range(len(LEVELS))]
    kept = 1 + int((np.diff(per_level) > 0.15).sum())
    assert kept >= 50, (kept, [round(m, 2) for m in per_level])


@pytest.mark.parametrize("profile, size", [("reel", (1200, 1600)), ("deep_dive", (2400, 1600))])
def test_black_is_video_black_through_one_tone_stage(tmp_path, lossless, profile, size):
    """A black still (its branch's tone curve, the film grade, the grain, the vignette) is Y16 +-1 in the master;
    the start commit stacked three black lifts to about Y22."""
    still = tmp_path / "black.png"
    Image.new("RGB", size, (0, 0, 0)).save(still)
    master = _compose(tmp_path, [still], 1.5, profile)
    w, h = (W, H) if profile == "reel" else (H, W)
    y = float(np.mean(_centre_means(master, w, h)[10:30]))
    assert abs(y - 16) <= 1, y


def test_the_picture_chain_is_16_bit_rgb_with_one_conversion_out():
    """The grade, grain, vignette and captions sit between one BT.709 read into gbrp16le and one conversion out."""
    from src.encoding import BT709_TO_RGB, RGB_TO_BT709
    chain = vc.picture_chain(vc.film_grade_filter(0.0), W, H, vignette_enable="", captions="subtitles='x.ass'")
    assert chain.startswith(f"{BT709_TO_RGB},format=gbrp16le,{vc.PHOTO_CURVE}")
    assert chain.endswith(f"subtitles='x.ass',{RGB_TO_BT709}") and chain.count("out_color_matrix") == 1
    assert "blend=all_mode=multiply" in chain and vc.picture_vignette(W, H) in chain
    assert "format=yuv420p" not in chain[:chain.index("subtitles")]
