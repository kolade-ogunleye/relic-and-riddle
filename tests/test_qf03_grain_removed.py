"""QF-03 (2026-11-06): no grain in the delivery master (operator decision: remove it).

The master's picture chain carried `noise=alls=8:allf=t+u`: temporal noise on every frame, most of the master's
bitrate at the same CRF on a still-image Reel, stripped again by the platforms' re-encodes. The contrast measurement
(graphics.graded_frame), which runs the master's chain, carried a seeded copy of it. Every input here is generated by
the test (a flat BT.709 clip, a flat grey frame, a sine narration); the master's encoder is pinned (libx264).
"""
import subprocess
from concurrent.futures import ThreadPoolExecutor

import numpy as np
from PIL import Image

from src import graphics
from src import video_composer as vc
from src.delivery_profiles import get_delivery_profile

W, H = 1080, 1920
TAGS = ["-colorspace", "bt709", "-color_primaries", "bt709", "-color_trc", "bt709", "-color_range", "tv"]


def _flat_clip(path, level=126, frames=30):
    uv = np.full((H // 2, W // 2), 128, np.uint8).tobytes()
    raw = (np.full((H, W), level, np.uint8).tobytes() + uv + uv) * frames
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "rawvideo", "-pix_fmt", "yuv420p", "-s", f"{W}x{H}", "-r", "30",
                    "-i", "-", "-vf", "setparams=range=tv:color_primaries=bt709:color_trc=bt709:colorspace=bt709",
                    "-c:v", "libx264", "-qp", "0", "-preset", "ultrafast", "-pix_fmt", "yuv420p", *TAGS, str(path)],
                   input=raw, check=True, timeout=300)
    return path


def _compose(tmp_path, clip, name, graphs, seconds=1.0):
    vo = tmp_path / "vo.wav"
    if not vo.exists():
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i", "sine=frequency=220:sample_rate=48000",
                        "-af", "volume=0.3", "-ac", "1", "-t", f"{seconds + 0.5:.2f}", str(vo)], check=True, timeout=60)
    out = tmp_path / f"{name}.mp4"
    vc.VideoComposer().compose_video([clip], vo, vo, [{"word": "Grey.", "start": 0.9, "dur": 0.1}], seconds, out,
                                     durations=[seconds], delivery_profile=get_delivery_profile("reel"))
    return out


def _lumas(path):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(path), "-f", "rawvideo", "-pix_fmt", "yuv420p", "-"],
                         capture_output=True, check=True, timeout=600).stdout
    n = W * H * 3 // 2
    a = np.frombuffer(raw, np.uint8)
    return [a[i * n:i * n + W * H].reshape(H, W)[H // 2 - 200:H // 2 + 200, W // 2 - 200:W // 2 + 200].astype(float)
            for i in range(len(a) // n)]


def _recording(monkeypatch, encoder):
    monkeypatch.setattr(vc, "_get_video_encoder", lambda: list(encoder))
    graphs, real = [], vc._run_ffmpeg

    def run(cmd, *a, **k):
        cmd = [str(c) for c in cmd]
        if "-filter_complex" in cmd:
            graphs.append(cmd[cmd.index("-filter_complex") + 1])
        return real(cmd, *a, **k)

    monkeypatch.setattr(vc, "_run_ffmpeg", run)
    return graphs


def test_a_static_picture_stays_static_in_the_master(tmp_path, monkeypatch):
    """A flat, unmoving clip: no noise filter in the master's graph, and its frames do not change from one to the
    next (the start commit's temporal grain changed each pixel by 1.67 codes a frame on average)."""
    graphs = _recording(monkeypatch, ["-c:v", "libx264", "-preset", "ultrafast", "-qp", "0"])
    master = _compose(tmp_path, _flat_clip(tmp_path / "grey_01.mp4"), "master", graphs)
    master_graph = next(g for g in graphs if "[v_final]" in g)
    assert "noise=" not in master_graph
    fr = _lumas(master)
    flicker = float(np.mean([np.abs(fr[i + 1] - fr[i]).mean() for i in range(3, 24)]))   # before the caption
    assert flicker < 0.5, flicker      # 0.13 (the 8-bit dither); the start commit's grain: 1.67


def test_two_renders_of_the_same_inputs_are_byte_identical(tmp_path, monkeypatch):
    """At the delivery CRF, picture, audio and container repeat identically."""
    from src.config import VIDEO_CRF, VIDEO_PRESET
    graphs = _recording(monkeypatch, ["-c:v", "libx264", "-preset", VIDEO_PRESET, "-crf", str(VIDEO_CRF)])
    clip = _flat_clip(tmp_path / "grey_01.mp4")
    a, b = (_compose(tmp_path, clip, f"master_{k}", graphs).read_bytes() for k in range(2))
    assert a == b


def test_calibration_cuts_the_same_samples_instead_of_racing_input_eof(tmp_path, monkeypatch):
    """Every calibration pass uses the programme's sample endpoint, including a cached re-render."""
    voice, bed = tmp_path / 'voice.wav', tmp_path / 'bed.wav'
    voice.write_bytes(b'voice')
    bed.write_bytes(b'bed')
    chains = []

    def measure(*args):
        chains.append(args[-1])
        return -14.0, -2.0

    def analyse(*args, **kwargs):   # QF-11: the gain is measured once, from the unlimited mix
        chains.append(args[2])
        return {"integrated_lufs": -14.0, "loudness_range_lu": 1.0, "true_peak_dbtp": -2.0, "frames": [],
                "passes": 1}

    monkeypatch.setattr(vc.VideoComposer, '_measure', staticmethod(measure))
    monkeypatch.setattr(vc.VideoComposer, '_analyse', staticmethod(analyse))
    composer = vc.VideoComposer()
    composer.calibrate_gain(voice, bed, end=1.0)
    assert len(chains) == 1
    assert all('atrim=end_sample=48000' in c and ',apad[bg_carved]' in c for c in chains)
    composer.calibrate_gain(voice, bed, end=2.0)
    assert len(chains) == 2  # a different endpoint cannot reuse the first programme's gain
    assert all('atrim=end_sample=96000' in c for c in chains[1:])


def test_concurrent_renders_keep_the_audio_and_container_identical(tmp_path, monkeypatch):
    """Independent composers under load must agree on the calibration and delivered bytes."""
    graphs = _recording(monkeypatch, ['-c:v', 'libx264', '-preset', 'ultrafast', '-crf', '18'])
    clip = _flat_clip(tmp_path / 'grey_01.mp4')
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 'lavfi', '-i',
                    'sine=frequency=220:sample_rate=48000', '-af', 'volume=0.3',
                    '-ac', '1', '-t', '1.5', str(tmp_path / 'vo.wav')], check=True)

    def render(k):
        return _compose(tmp_path, clip, f'parallel_{k}', graphs).read_bytes()

    with ThreadPoolExecutor(max_workers=3) as pool:
        rendered = list(pool.map(render, range(3)))
    assert rendered[0] == rendered[1] == rendered[2]


def test_the_contrast_measurement_runs_the_master_chain_without_grain(tmp_path):
    """graphics.graded_frame measures a graphic on the master's chain: a flat grey frame comes back flat."""
    out = graphics.graded_frame(Image.new("RGB", (540, 960), (128, 128, 128)), tmp_path)
    assert out is not None
    a = np.asarray(out, np.float32)[100:-100, 100:-100]
    assert float(a.std(axis=(0, 1)).max()) < 1.4, a.std(axis=(0, 1))   # the 8-bit dither alone; grain took it to 2.2
